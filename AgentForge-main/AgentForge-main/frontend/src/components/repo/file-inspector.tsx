"use client";

import { useQuery } from "@tanstack/react-query";
import { formatDistanceToNow } from "date-fns";
import { Bot, FlaskConical, Lightbulb, ShieldCheck } from "lucide-react";
import { getRun, listKnowledge } from "@/lib/api";
import { Skeleton } from "@/components/ui/skeleton";

export function FileInspector({ runId, path }: { runId: string; path: string | null }) {
  const { data: run } = useQuery({
    queryKey: ["run-detail", runId],
    queryFn: () => getRun(runId),
  });

  const { data: knowledge } = useQuery({
    queryKey: ["knowledge", runId],
    queryFn: () => listKnowledge(runId),
  });

  if (!path) {
    return (
      <div className="flex h-full items-center justify-center p-6 text-center text-sm text-muted-foreground">
        Select a file to see AI context.
      </div>
    );
  }

  if (!run) {
    return (
      <div className="space-y-3 p-4">
        <Skeleton className="h-4 w-2/3" />
        <Skeleton className="h-4 w-1/2" />
      </div>
    );
  }

  const relevantKnowledge = (knowledge?.entries ?? []).filter(
    (entry) => entry.category === "architecture_decision" || entry.category === "coding_standard",
  );

  return (
    <div className="flex h-full flex-col overflow-y-auto p-4 text-sm">
      <div className="mb-4">
        <p className="truncate font-mono text-xs text-muted-foreground">{path}</p>
      </div>

      <dl className="space-y-3">
        <div className="flex items-start gap-2">
          <Bot className="mt-0.5 size-3.5 shrink-0 text-primary" />
          <div>
            <dt className="text-xs text-muted-foreground">Generated by</dt>
            <dd className="text-foreground">
              Developer agent
              {run.completed_at && (
                <span className="text-muted-foreground">
                  {" "}
                  · {formatDistanceToNow(new Date(run.completed_at), { addSuffix: true })}
                </span>
              )}
            </dd>
          </div>
        </div>

        <div className="flex items-start gap-2">
          <FlaskConical className="mt-0.5 size-3.5 shrink-0 text-muted-foreground" />
          <div>
            <dt className="text-xs text-muted-foreground">Test status (run-wide)</dt>
            <dd className="text-foreground capitalize">{run.testing_result}</dd>
          </div>
        </div>

        <div className="flex items-start gap-2">
          <ShieldCheck className="mt-0.5 size-3.5 shrink-0 text-muted-foreground" />
          <div>
            <dt className="text-xs text-muted-foreground">Review status (run-wide)</dt>
            <dd className="text-foreground">
              {run.review_passed ? "Passed" : "Pending"} · {run.review_score.toFixed(1)}/10
            </dd>
          </div>
        </div>
      </dl>

      {relevantKnowledge.length > 0 && (
        <div className="mt-5 border-t border-border/60 pt-4">
          <h4 className="mb-2 flex items-center gap-1.5 text-xs font-medium text-muted-foreground">
            <Lightbulb className="size-3.5" />
            Related project knowledge
          </h4>
          <ul className="space-y-2.5">
            {relevantKnowledge.map((entry) => (
              <li key={entry.id} className="rounded-lg bg-surface-2/60 p-2.5">
                <p className="text-xs font-medium text-foreground">{entry.title}</p>
                <p className="mt-0.5 text-xs text-muted-foreground">{entry.content}</p>
              </li>
            ))}
          </ul>
        </div>
      )}

      <p className="mt-5 border-t border-border/60 pt-3 text-xs text-muted-foreground/70">
        Per-file generation attribution is run-wide today — the backend only tracks which files
        the Developer agent materialized, not per-file timestamps or Documentation-agent output.
      </p>
    </div>
  );
}
